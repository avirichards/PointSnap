import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const output = 'docs/evidence/results-cleanup-2026-09-06';
await mkdir(output, { recursive:true });
const browser = await chromium.launch({channel:'chrome',headless:true});
const report = {liveCollectorsRequested:false, checks:[], screenshots:[]};
try {
  const context = await browser.newContext({viewport:{width:1440,height:1000},colorScheme:'dark',reducedMotion:'reduce'});
  const page = await context.newPage(), errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/api/search?**',r=>r.abort());
  await page.route('**/api/display-currency',r=>r.fulfill({json:{currency:'USD',rates:{USD:{rate:1,date:'2026-09-06'},EUR:{rate:.9,date:'2026-09-06'}}}}));
  const go = async path=>{ await page.goto(`http://127.0.0.1:3001${path}`); await page.waitForTimeout(800); };
  const capture = async name=>{await page.screenshot({path:`${output}/${name}.png`});report.screenshots.push(name);};
  await go('/search?origin=JFK&dest=LHR&departDate=2026-10-07&pax=1&minCabin=Y');
  assert.equal(await page.getByRole('button',{name:'Route map',exact:true}).count(),0);
  assert.equal(await page.locator('.route-globe').count(),0);
  await go('/search');
  await page.locator('.globe-svg').waitFor();
  report.checks.push('Results route map and control removed; homepage globe retained');
  await go('/design-preview');
  assert.equal(await page.getByRole('button',{name:'Display preferences',exact:true}).count(),0);
  await page.getByRole('button',{name:'Cabin',exact:true}).click();
  await page.getByRole('checkbox',{name:'Business',exact:true}).locator('..').click();
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.filter-all-trigger .filter-count').textContent(),'1');
  await page.locator('.filter-all-trigger').click();
  const summary=page.locator('.filter-display-preferences summary');
  await summary.click();
  await page.getByRole('combobox',{name:'Display currency',exact:true}).selectOption('EUR');
  await page.getByRole('radio',{name:/^24-hour/}).locator('..').click();
  await page.getByRole('radio',{name:'Roomy',exact:true}).locator('..').click();
  await page.locator('.filter-sheet-body').evaluate(el=>{el.scrollTop=el.scrollHeight;});
  assert.equal(await page.locator('.filter-sheet').evaluate(el=>el.scrollTop),0,'Sheet header must stay fixed while browsing preferences');
  await capture('desktop-display-preferences');
  assert.equal(await page.locator('.filter-all-trigger .filter-count').textContent(),'1');
  await page.getByRole('button',{name:'Reset all',exact:true}).click();
  assert.equal(await page.getByRole('combobox',{name:'Display currency',exact:true}).inputValue(),'EUR');
  assert.equal(await page.getByRole('radio',{name:/^24-hour/}).isChecked(),true);
  assert.equal(await page.getByRole('radio',{name:'Roomy',exact:true}).isChecked(),true);
  await page.getByRole('button',{name:/^Show \d+ flights?$/}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  assert.equal(await page.locator('.award-results').getAttribute('data-density'),'comfortable');
  assert.match(await page.locator('.award-results').textContent(),/18:30/);
  assert.match(await page.locator('.award-results').textContent(),/EUR/);
  report.checks.push('Currency/time/layout update results immediately; display choices do not count as filters or reset with Reset all');
  await page.locator('.award-results').evaluate(el=>el.scrollIntoView({block:'start',behavior:'instant'}));
  await capture('desktop-results');
  await page.reload();
  await page.locator('.filter-all-trigger').click();
  await summary.click();
  assert.equal(await page.getByRole('combobox',{name:'Display currency',exact:true}).inputValue(),'EUR');
  assert.equal(await page.getByRole('radio',{name:/^24-hour/}).isChecked(),true);
  assert.equal(await page.getByRole('radio',{name:'Roomy',exact:true}).isChecked(),true);
  report.checks.push('All three display settings persist after reload');
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.setViewportSize({width:390,height:844});
  await page.locator('.filter-all-trigger').click();
  await summary.scrollIntoViewIfNeeded();
  await summary.focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('.filter-display-preferences').getAttribute('open'),'');
  await page.getByRole('radio',{name:'Compact',exact:true}).locator('..').click();
  await page.getByRole('radio',{name:/^12-hour/}).locator('..').click();
  await page.getByRole('combobox',{name:'Display currency',exact:true}).selectOption('USD');
  await page.locator('.filter-sheet-body').evaluate(el=>{el.scrollTop=el.scrollHeight;});
  assert.equal(await page.locator('.filter-sheet').evaluate(el=>el.scrollTop),0,'Sheet header must stay fixed while browsing preferences');
  await capture('mobile-display-preferences');
  const dialog = await page.getByRole('dialog').boundingBox();
  assert.ok(dialog.x >=0 && dialog.x+dialog.width<=390);
  await page.getByRole('button',{name:/^Show \d+ flights?$/}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  assert.equal(await page.locator('.award-results').getAttribute('data-density'),'compact');
  assert.match(await page.locator('.award-results').textContent(),/6:30 PM/);
  report.checks.push('Phone menu has no horizontal overflow; keyboard disclosure and settings work; changes apply to results');
  assert.deepEqual(errors,[]);
  await writeFile(`${output}/checks.json`,JSON.stringify({...report,browserErrors:errors},null,2)+'\n');
  console.log(JSON.stringify(report));
} finally {await browser.close();}
